  '  });',
  '',
  '  it("R2: no flag when duplicate values are within tolerance", () => {',
  '    const c = detectConflicts({ facts: [fact({ id: "f1", kind: "lab", rawName: "Hb", canonicalName: "Hemoglobin", value: "10.0" }), fact({ id: "f2", kind: "lab", rawName: "Hemoglobin", canonicalName: "Hemoglobin", value: "10.04" })], intakeAllergies: [], intakeNoKnownAllergies: false, intakeMedications: [] });',
