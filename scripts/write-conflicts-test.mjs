  '  });',
  '',
  '  it("R4: flags sex-specific analyte mismatch as info (not warning)", () => {',
  '    const c = detectConflicts({ facts: [fact({ id: "f1", kind: "lab", rawName: "PSA", value: "2.0" })], intakeAllergies: [], intakeNoKnownAllergies: false, intakeMedications: [], sex: "female" });',
